#!/usr/bin/env node
// Writes calls/fuzz1.txt .. fuzz4.txt: random mixes of every lcd call with seeded random arguments,
// mostly on and around the screen, sometimes far off or at the int32 limits. Deterministic: the same
// files every run. Triangles keep their rows within +-200000 and filled circles their radius within
// 100000, because engine.js loops over every row of them (the C code skips invisible rows) and the
// reference must stay quick to compute.
'use strict';
const fs = require('fs');
const path = require('path');

function mulberry32(seed) {
  return () => {
    seed = (seed + 0x6D2B79F5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const STRINGS = ['', 'a', 'abc', 'StickTime', 'Race (10 laps, 3 AI)', '60 fps', '\\xc2\\xb0/s', '< Hoop Forest >',
  '\\xc4\\x8c\\xc4\\x87\\xc5\\xbe\\xc5\\xa1\\xc4\\x91', '\\xf0\\x9f\\x98\\x80', 'x\\ty', 'W', 'WWWWWWWWWWWWWWWW',
  'Lap 1/3  0:12.34', '\\" quoted \\\\'];

function generate(seed, n, adv) {
  const R = mulberry32(seed);
  const int = (lo, hi) => lo + Math.floor(R() * (hi - lo + 1));
  const pick = (a) => a[Math.floor(R() * a.length)];
  const coord = (span) => {
    const r = R();
    if (r < 0.7) return int(-50, span + 50);
    if (r < 0.9) return int(-2000, 2000);
    if (r < 0.98) return int(-100000, 100000);
    return pick([-2147483648, -2147483647, 2147483647, 2147483646, -1000000000, 1000000000]);
  };
  const x = () => coord(640), y = () => coord(480);
  const size = () => { const r = R(); return r < 0.8 ? int(-60, 300) : r < 0.95 ? int(-3000, 3000) : coord(640); };
  const color = () => {
    const r = R();
    if (r < 0.4) return '0x' + (((int(0, 0xFFFF) << 16) | 0x8000 | (R() < 0.5 ? 0 : int(0, 0x7FFF))) >>> 0).toString(16).toUpperCase();
    if (r < 0.8) return '0x' + (((int(0, 34) << 16) | (R() < 0.5 ? 0 : int(0, 0x7FFF))) >>> 0).toString(16).toUpperCase();
    return String(int(-2147483648, 2147483647));
  };
  const opa = () => (R() < 0.85 ? int(0, 15) : int(-40, 40));
  const textFlags = () => {
    let f = int(0, 15) << 8;
    for (const bit of [0x01, 0x02, 0x04, 0x08, 0x80, 0x10, 0x20, 0x1000, 0x2000]) if (R() < 0.3) f |= bit;
    return '0x' + ((((R() < 0.5 ? int(0, 0xFFFF) << 16 | 0x8000 : int(0, 34) << 16)) | f) >>> 0).toString(16).toUpperCase();
  };
  const triY = () => { const v = y(); return Math.max(-200000, Math.min(200000, v)); };
  const L = [`# generated by fuzz.js (seed ${seed}): do not edit`, `adv ${adv}`, `clear ${color()}`];
  for (let i = 0; i < n; i++) {
    const r = R();
    if (r < 0.03) { L.push('snap'); continue; }
    if (r < 0.05) { L.push(`clear ${color()}`); continue; }
    if (r < 0.2) { L.push(`drawLine ${x()} ${y()} ${x()} ${y()} ${R() < 0.8 ? int(0, 255) : int(-1000, 1000)} ${color()}`); continue; }
    if (r < 0.33) { L.push(`drawFilledRectangle ${x()} ${y()} ${size()} ${size()} ${color()} ${opa()}`); continue; }
    if (r < 0.47) { L.push(`drawFilledTriangle ${x()} ${triY()} ${x()} ${triY()} ${x()} ${triY()} ${color()} ${opa()}`); continue; }
    if (r < 0.52) { L.push(`drawRectangle ${x()} ${y()} ${size()} ${size()} ${color()} ${R() < 0.7 ? int(0, 6) : int(-20, 200)} ${opa()}`); continue; }
    if (r < 0.57) { L.push(`invertRect ${x()} ${y()} ${size()} ${size()}`); continue; }
    if (r < 0.62) { L.push(`drawFilledCircle ${x()} ${y()} ${R() < 0.9 ? int(-5, 300) : int(-100, 100000)} ${color()}`); continue; }
    if (r < 0.67) { L.push(`drawCircle ${x()} ${y()} ${R() < 0.9 ? int(-50, 400) : coord(100000)} ${color()}`); continue; }
    if (r < 0.7) { L.push(`drawPoint ${x()} ${y()} ${color()}`); continue; }
    if (r < 0.74) { L.push(`drawTriangle ${x()} ${y()} ${x()} ${y()} ${x()} ${y()} ${color()}`); continue; }
    if (r < 0.77) { L.push(`drawGauge ${x()} ${y()} ${size()} ${size()} ${int(-50, 150)} ${R() < 0.8 ? int(-10, 100) : 0} ${color()}`); continue; }
    if (r < 0.87) { L.push(`drawText ${x()} ${y()} "${pick(STRINGS)}" ${textFlags()}`); continue; }
    if (r < 0.92) { L.push(`drawNumber ${x()} ${y()} ${R() < 0.8 ? int(-100000, 100000) : int(-2147483648, 2147483647)} ${textFlags()}`); continue; }
    if (r < 0.96) { L.push(`drawTimer ${x()} ${y()} ${R() < 0.8 ? int(-10000, 10000) : int(-2147483648, 2147483647)} ${textFlags()}`); continue; }
    L.push(`sizeText "${pick(STRINGS)}" ${textFlags()}`);
  }
  return L.join('\n') + '\n';
}

const dir = path.join(__dirname, 'calls');
[[1, 7.3], [2, 5], [3, 6.25], [4, 9.7]].forEach(([seed, adv]) => {
  fs.writeFileSync(path.join(dir, `fuzz${seed}.txt`), generate(seed, 600, adv));
});
console.log('wrote fuzz1..4.txt');
