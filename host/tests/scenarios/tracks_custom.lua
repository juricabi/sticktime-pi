-- Custom tracks c1..c8: a gallery track flies; broken slots never crash the game.
dofile(SCEN_DIR .. "/lib.lua")
local f = assert(io.open(GALLERY_TRACK, "rb"))
local text = f:read("a")
f:close()
frames(30)
sd_write("/SCRIPTS/TOOLS/StickTimeTracks/c1.txt", text)
sd_write("/SCRIPTS/TOOLS/StickTimeTracks/c2.txt", "Bad\n1 5\n")        -- format + id, no seed (game-api §10 A)
sd_write("/SCRIPTS/TOOLS/StickTimeTracks/c3.txt", "")
sd_write("/SCRIPTS/TOOLS/StickTimeTracks/c4.txt", "\255\254garbage\0\0")
check(reload(), "reload with custom tracks: " .. tostring(err()))
frames(30)
no_error("custom load")
local top = test("info")
check(top == 9, "highest track should be 9 (c1), got " .. tostring(top))
test("track", 9)
test("start", 2)
frames(360)
no_error("fly c1")
shot("custom_c1")
to_menu()
-- the saved track is a slot that then breaks: the next load must still work
sd_write("/SCRIPTS/TOOLS/StickTimeTracks/c1.txt", "Bad\n1 5\n")
check(reload(), "reload after c1 broke: " .. tostring(err()))
frames(30)
no_error("broken saved slot")
expect_state(MENU, "menu after a broken saved slot")
return true
