/* the partitioned convolution against a direct one (all three stages, zero latency) */
static void test_convolver(void) {
  const int nir = 40000, nin = 70000;
  float *ir = malloc(sizeof(float) * 2 * nir);
  float *in = malloc(sizeof(float) * 2 * nin), *out = malloc(sizeof(float) * 2 * nin);
  dsp_rng_t r;
  dsp_rng_seed(&r, 3);
  for (int c = 0; c < 2; c++)
    for (int i = 0; i < nir; i++) ir[c * nir + i] = (float)((dsp_rng(&r) * 2 - 1) * pow(1 - (double)i / nir, 3.5));
  for (int i = 0; i < 2 * nin; i++) in[i] = (float)(dsp_rng(&r) * 2 - 1) * (i < nin ? 1.0f : 0.5f);
  mconv_ir_t *h = mconv_ir_new(ir, ir + nir, nir, 48000);
  mconv_t *c = mconv_new(h);
  CHECK(h && c);
  if (!h || !c) return;
  for (int q = 0; q + MQ <= nin; q += MQ) mconv_process(c, in + q, in + nin + q, out + q, out + nin + q);
  double sc = mconv_ir_scale(h), worst = 0, ref_rms = 0;
  int probes = 0;
  for (int k = 0; k < 400; k++) {
    int n = (int)(dsp_rng(&r) * (nin / MQ * MQ - 1));
    if (k < 8) n = k * 9001 + 5;             /* early frames too (before the later stages start) */
    for (int ch = 0; ch < 2; ch++) {
      double y = 0;
      const float *x = in + ch * nin, *hh = ir + ch * nir;
      for (int j = 0; j < nir && j <= n; j++) y += (double)hh[j] * x[n - j];
      y *= sc;
      worst = fmax(worst, fabs(y - out[ch * nin + n]));
      ref_rms += y * y;
      probes++;
    }
  }
  ref_rms = sqrt(ref_rms / probes);
  printf("convolver: max error %.2e of rms %.3f, scale %.6f\n", worst, ref_rms, sc);
  CHECK(worst < 1e-4 * ref_rms * 100 && worst < 1e-3);
  /* the browser's IR (2.6 s of decaying noise) normalizes to about 0.00565 at 48 kHz (notes 6.7) */
  int nb = (int)floor(48000 * 2.6);
  float *bir = malloc(sizeof(float) * 2 * nb);
  for (int i = 0; i < 2 * nb; i++) bir[i] = (float)((dsp_rng(&r) * 2 - 1) * pow(1 - (double)(i % nb) / nb, 3.5));
  mconv_ir_t *hb = mconv_ir_new(bir, bir + nb, nb, 48000);
  CHECK(hb != NULL);
  if (hb) CHECK_NEAR(mconv_ir_scale(hb), 0.00565, 0.0002);
  mconv_ir_free(hb);
  free(bir);
  mconv_free(c);
  mconv_ir_free(h);
  free(ir); free(in); free(out);
}

/* AudioParam timelines: ramps, cancel (a running ramp jumps back), the intended cancel, fill == value */
static void test_param(void) {
  mparam_t p;
  mparam_init(&p, 5);
  CHECK_NEAR(mparam_value(&p, 0.3), 5, 0);
  mparam_set(&p, 1, 1.0);
  mparam_lin(&p, 3, 2.0);
  mparam_exp(&p, 12, 4.0);
  CHECK_NEAR(mparam_value(&p, 0.5), 5, 0);
  CHECK_NEAR(mparam_value(&p, 1.5), 2, 1e-12);
  CHECK_NEAR(mparam_value(&p, 3.0), 6, 1e-9);              /* 3 * (12/3)^0.5 */
  CHECK_NEAR(mparam_value(&p, 9.0), 12, 0);
  double buf[256];
  mparam_t q = p;
  mparam_fill(&q, 47000, 256, 48000, buf);                  /* across t = 1.0 (frame 48000) */
  bool same = true;
  for (int i = 0; i < 256; i++) same = same && fabs(buf[i] - mparam_value(&p, (47000.0 + i) / 48000)) < 1e-9;
  CHECK(same);
  q = p;
  mparam_fill(&q, 100000, 256, 48000, buf);                 /* inside the exponential ramp */
  same = true;
  for (int i = 0; i < 256; i++) same = same && fabs(buf[i] / mparam_value(&p, (100000.0 + i) / 48000) - 1) < 1e-9;
  CHECK(same);
  /* cancel(t) removes a ramp ending at or after t: the value jumps back to the ramp's start */
  mparam_init(&p, 18000);
  mparam_set(&p, 320, 1.0);
  mparam_exp(&p, 18000, 3.0);
  q = p;
  mparam_cancel(&q, 3.0);
  CHECK_NEAR(mparam_value(&q, 2.9), 320, 0);
  q = p;
  mparam_cancel_keep_ending(&q, 3.0 + 1e-9);
  CHECK_NEAR(mparam_value(&q, 2.9) / (320 * pow(18000.0 / 320, 0.95)), 1, 1e-6);   /* the ramp now ends 1 ns later */
  mparam_set(&q, 18000, 3.0 + 1e-9);
  CHECK_NEAR(mparam_value(&q, 3.5), 18000, 0);
  double v;
  mparam_init(&p, 2);
  CHECK(mparam_constant(&p, 0, 128, 48000, &v) && v == 2);
  mparam_set(&p, 4, 0.001);
  CHECK(!mparam_constant(&p, 0, 128, 48000, &v));
  CHECK(mframe_at(0.1, 48000) == 4800);
  CHECK(mframe_at(0.57619047619, 48000) == 27658);
}

