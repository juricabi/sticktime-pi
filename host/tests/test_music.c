static double rms_render(music_t *m, double secs, float *pk) {
  float L[333], R[333];
  int64_t n = (int64_t)(secs * 48000), done = 0;
  double acc = 0;
  float p = 0;
  while (done < n) {
    int c = (int)(n - done < 333 ? n - done : 333);
    memset(L, 0, sizeof L); memset(R, 0, sizeof R);
    music_render(m, L, R, c);
    for (int i = 0; i < c; i++) { acc += (double)L[i] * L[i] + (double)R[i] * R[i]; p = fmaxf(p, fmaxf(fabsf(L[i]), fabsf(R[i]))); }
    done += c;
  }
  if (pk) *pk = p;
  return sqrt(acc / (2.0 * (double)n));
}

