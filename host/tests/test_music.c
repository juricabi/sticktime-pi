/* seed 1, exact browser scheduling: the event log, the songs' titles, per-bar levels vs Chromium */
static void test_generator_vs_browser(void) {
  const int sr = 48000;
  int64_t t0 = plat_now_us();
  music_t *m = music_new(sr, 1, NULL);
  CHECK(m != NULL);
  if (!m) return;
  evlog_t e = { 0xcbf29ce484222325ULL, 0, 0, { 0 }, true };
  music_test_log(m, ev_cb, &e);
  music_test_exact(m, true);
  char np[128];
  music_now_playing(m, np, sizeof np);
  CHECK_STR(np, "");                           /* off by default */
  music_set(m, true, 0.6f, AUDIO_MUSIC_GENERATED);
  const double bar = 240.0 / 126;
  double acc[72] = { 0 }, peak = 0;
  int64_t cnt[72] = { 0 };
  const int B = 480;                           /* not a multiple of the 128-frame quantum */
  float L[480], R[480];
  int64_t total = (int64_t)(150.0 * sr), done = 0;
  int64_t rt = 0;
  bool title0 = false, title1 = false;
  while (done < total) {
    memset(L, 0, sizeof L); memset(R, 0, sizeof R);
    int64_t a = plat_now_us();
    music_render(m, L, R, B);
    rt += plat_now_us() - a;
    for (int i = 0; i < B; i++) {
      double t = (double)(done + i) / sr;
      int k = (int)floor((t - 0.1) / bar);
      if (t >= 0.1 && k >= 0 && k < 72) {
        acc[k] += (double)L[i] * L[i] + (double)R[i] * R[i]; cnt[k] += 2;
        if (fabs(L[i]) > peak) peak = fabs(L[i]);
        if (fabs(R[i]) > peak) peak = fabs(R[i]);
      }
    }
    done += B;
    if (done == 10 * B) { music_now_playing(m, np, sizeof np); title0 = !strcmp(np, "Generated: Bb minor, 126 BPM"); }
    if (!title1 && (double)done / sr > EV_SONG1_AT + 0.5) {
      music_now_playing(m, np, sizeof np);
      title1 = !strcmp(np, "Generated: G minor, 120 BPM");
      if (!title1) fprintf(stderr, "title after the song change: %s\n", np);
    }
  }
  CHECK(title0);
  CHECK(title1);
  CHECK_INT(music_test_frames(m), total);
  /* the instrument calls: the same list as the browser's (count, digest, the first ones) */
  CHECK_INT(e.n, EV_COUNT);
  CHECK(e.h == EV_FNV);
  CHECK(e.first_ok);
  for (int i = 0; i < 10; i++) CHECK_INT(e.song0[i], EV_SONG0[i].n);
  /* levels: every bar of the first song within 0.5 dB of Chromium's render (notes 12.7) */
  double worst = 0;
  for (int k = 0; k < 72; k++) {
    double d = 10 * log10(acc[k] / (double)cnt[k]) - BAR_DB[k];
    if (fabs(d) > fabs(worst)) worst = d;
  }
  printf("generator: bars within %.3f dB of Chromium, peak %.2f dBFS (Chromium %.2f), %.2f%% of real time\n",
         worst, db(peak), SONG_PEAK_DB, 100.0 * (double)rt / 1e6 / 150.0);
  CHECK(fabs(worst) < 0.5);
  CHECK(fabs(db(peak) - SONG_PEAK_DB) < 1.0);
  CHECK(music_test_voices(m) < 96);            /* the pool never ran out */
  music_free(m);
  printf("generator vs browser: %.1f s\n", (double)(plat_now_us() - t0) / 1e6);
}

