static double db(double x) { return 20 * log10(x > 1e-12 ? x : 1e-12); }

static uint64_t fnv(uint64_t h, const char *s) {
  for (; *s; s++) { h ^= (unsigned char)*s; h *= 0x100000001b3ULL; }
  return h;
}

static const char *tmpdir(void) {
  const char *e = getenv("MUSIC_TEST_TMP");
  return e && *e ? e : "build/test-music";
}

static int b64v(char c) {
  if (c >= 'A' && c <= 'Z') return c - 'A';
  if (c >= 'a' && c <= 'z') return c - 'a' + 26;
  if (c >= '0' && c <= '9') return c - '0' + 52;
  if (c == '+') return 62;
  if (c == '/') return 63;
  return -1;
}
static size_t b64dec(const char *s, unsigned char *out) {
  size_t n = 0;
  int acc = 0, bits = 0;
  for (; *s; s++) {
    int v = b64v(*s);
    if (v < 0) continue;
    acc = (acc << 6) | v; bits += 6;
    if (bits >= 8) { bits -= 8; out[n++] = (unsigned char)((acc >> bits) & 0xFF); }
  }
  return n;
}

static void path_in(char *out, size_t n, const char *name) { snprintf(out, n, "%s/%s", tmpdir(), name); }

static void write_bytes(const char *name, const void *p, size_t n) {
  char path[600];
  path_in(path, sizeof path, name);
  FILE *f = fopen(path, "wb");
  if (!f) { fprintf(stderr, "can't write %s\n", path); return; }
  if (n) fwrite(p, 1, n, f);
  fclose(f);
}

static void write_b64(const char *name, const char *b64) {
  unsigned char *buf = malloc(strlen(b64));
  size_t n = b64dec(b64, buf);
  write_bytes(name, buf, n);
  free(buf);
}

/* 16-bit PCM WAV: frames of a sine (fl on L, fr on R) at amplitude a */
static void write_wav(const char *name, int rate, int ch, int frames, double fl, double fr, double a) {
  size_t bytes = (size_t)frames * ch * 2;
  unsigned char *b = malloc(44 + bytes);
  uint32_t v;
  memcpy(b, "RIFF", 4); v = (uint32_t)(36 + bytes); memcpy(b + 4, &v, 4);
  memcpy(b + 8, "WAVEfmt ", 8); v = 16; memcpy(b + 16, &v, 4);
  uint16_t s16 = 1; memcpy(b + 20, &s16, 2); s16 = (uint16_t)ch; memcpy(b + 22, &s16, 2);
  v = (uint32_t)rate; memcpy(b + 24, &v, 4); v = (uint32_t)(rate * ch * 2); memcpy(b + 28, &v, 4);
  s16 = (uint16_t)(ch * 2); memcpy(b + 32, &s16, 2); s16 = 16; memcpy(b + 34, &s16, 2);
  memcpy(b + 36, "data", 4); v = (uint32_t)bytes; memcpy(b + 40, &v, 4);
  int16_t *d = (int16_t *)(b + 44);
  for (int i = 0; i < frames; i++)
    for (int c = 0; c < ch; c++) {
      double f = c == 0 ? fl : fr;
      d[i * ch + c] = (int16_t)lrint(32767.0 * a * sin(2 * M_PI * f * i / rate));
    }
  write_bytes(name, b, 44 + bytes);
  free(b);
}

static void remove_in(const char *name) {
  char path[600];
  path_in(path, sizeof path, name);
  plat_remove(path);
}

